test_that('"arma_spec" validation works as intended', {
  expect_error(arma_spec(orders = "hello"), "invalid class \"arma_spec\" object: invalid object for slot \"orders\" in class \"arma_spec\": got class \"character\", should be or extend class \"numeric\"")
  expect_error(arma_spec(long_memo = "hello"), "invalid object for slot \"long_memo\" in class \"arma_spec\": got class \"character\", should be or extend class \"logical\"")
  expect_no_error(arma_spec(long_memo = TRUE))
  expect_no_error(arma_spec(long_memo = FALSE))
  expect_error(arma_spec(long_memo = c(FALSE, TRUE)), "@long_memo must be of length one")
  expect_error(arma_spec(long_memo = logical(0)), "@long_memo must be of length one")
  expect_no_error(arma_spec(orders = c(1, 1)))
  expect_no_error(arma_spec(orders = c(0, 0)))
  expect_no_error(arma_spec(orders = c(1, 0)))
  expect_no_error(arma_spec(orders = c(0, 1)))
  expect_no_error(arma_spec(orders = c(2, 2)))
  expect_no_error(arma_spec(orders = c(2, 1)))
  expect_no_error(arma_spec(orders = c(1, 2)))
  expect_error(arma_spec(orders = c(1, 1, 1)), "@orders must be of length two and both elements must be at least zero")
  expect_error(arma_spec(orders = numeric(0)), "@orders must be of length two and both elements must be at least zero")
  expect_error(arma_spec(orders = c(0, -1)), "@orders must be of length two and both elements must be at least zero")
  expect_error(arma_spec(orders = c(-1, 0)), "@orders must be of length two and both elements must be at least zero")
})
